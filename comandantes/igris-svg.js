// Estados de animación: se aplican como clase en el <svg class="ig">
// idle (respiración por defecto) | walk | attack | guard | hit | summon
const IGRIS_STATES = ['idle', 'walk', 'attack', 'guard', 'hit', 'summon'];

function setIgrisAnim(svgEl, state, duration = 0) {
  if (!svgEl) return;
  IGRIS_STATES.forEach(s => svgEl.classList.remove('ig-' + s));
  svgEl.classList.add('ig-' + state);
  if (duration > 0) {
    setTimeout(() => {
      svgEl.classList.remove('ig-' + state);
      svgEl.classList.add('ig-idle');
    }, duration);
  }
}