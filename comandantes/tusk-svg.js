// Estados de animación: clase en el <svg class="ig">
// idle (respiración + parpadeo + orbe flotando) | walk (flota) | attack (tajo + orbe sube y brilla)
// guard | hit | summon
const TUSK_STATES = ['idle', 'walk', 'attack', 'guard', 'hit', 'summon'];

function setTuskAnim(svgEl, state, duration = 0) {
  if (!svgEl) return;
  TUSK_STATES.forEach(s => svgEl.classList.remove('ig-' + s));
  svgEl.classList.add('ig-' + state);
  if (duration > 0) {
    setTimeout(() => {
      svgEl.classList.remove('ig-' + state);
      svgEl.classList.add('ig-idle');
    }, duration);
  }
}
