// Estados de animación: clase en el <svg class="ig">
// idle (respiración por defecto) | walk | attack (tajo de hacha) | guard | hit | summon
const IRON_STATES = ['idle', 'walk', 'attack', 'guard', 'hit', 'summon'];

function setIronAnim(svgEl, state, duration = 0) {
  if (!svgEl) return;
  IRON_STATES.forEach(s => svgEl.classList.remove('ig-' + s));
  svgEl.classList.add('ig-' + state);
  if (duration > 0) {
    setTimeout(() => {
      svgEl.classList.remove('ig-' + state);
      svgEl.classList.add('ig-idle');
    }, duration);
  }
}
