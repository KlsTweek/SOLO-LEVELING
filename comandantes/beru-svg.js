// Estados de animación: clase en el <svg class="ig">
// idle (vibración suave + alas) | walk (paso de piernas + flota) | attack (garra + alas abiertas)
// guard | hit | summon
const BERU_STATES = ['idle', 'walk', 'attack', 'guard', 'hit', 'summon'];

function setBeruAnim(svgEl, state, duration = 0) {
  if (!svgEl) return;
  BERU_STATES.forEach(s => svgEl.classList.remove('ig-' + s));
  svgEl.classList.add('ig-' + state);
  if (duration > 0) {
    setTimeout(() => {
      svgEl.classList.remove('ig-' + state);
      svgEl.classList.add('ig-idle');
    }, duration);
  }
}
