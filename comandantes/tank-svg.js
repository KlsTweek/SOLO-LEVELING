// Estados de animación: clase en el <svg class="ig">
// idle (respiración por defecto, la del juego) | walk | attack | guard | hit | summon
const TANK_STATES = ['idle', 'walk', 'attack', 'guard', 'hit', 'summon'];

function setTankAnim(svgEl, state, duration = 0) {
  if (!svgEl) return;
  TANK_STATES.forEach(s => svgEl.classList.remove('ig-' + s));
  svgEl.classList.add('ig-' + state);
  if (duration > 0) {
    setTimeout(() => {
      svgEl.classList.remove('ig-' + state);
      svgEl.classList.add('ig-idle');
    }, duration);
  }
}
